function table(header, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0)
  const scale = CONTENT_WIDTH / total
  const w = widths.map((x) => Math.round(x * scale))
  w[w.length - 1] += CONTENT_WIDTH - w.reduce((a, b) => a + b, 0)
  const border = { style: BorderStyle.SINGLE, size: 4, color: 'A0A4AC' }
  const cell = (text, i, head) => new TableCell({
    width: { size: w[i], type: WidthType.DXA },
    borders: { top: border, bottom: border, left: border, right: border },
    shading: head ? { fill: 'E9EEFB', type: ShadingType.CLEAR, color: 'auto' } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new Paragraph({ children: runs(text, { size: 24, bold: head || undefined }), spacing: { line: 260 } })],
  })
  return new Table({
    width: { size: CONTENT_WIDTH, type: WidthType.DXA },
    columnWidths: w,
    rows: [
      new TableRow({ tableHeader: true, children: header.map((h, i) => cell(h, i, true)) }),
      ...rows.map((r) => new TableRow({ children: r.map((c, i) => cell(c, i, false)) })),
    ],
  })
}

let figureNo = 0
let tableNo = 0
function pngSize(file) {
  const b = fs.readFileSync(file)
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) }
}
function figure(name, caption, maxWidthPx = 620) {
  const file = path.join(IMG, name)
  const { w, h } = pngSize(file)
  let width = Math.min(maxWidthPx, 620)
  let height = Math.round((h / w) * width)
  if (height > 820) { height = 820; width = Math.round((w / h) * height) }
  figureNo += 1
  return [
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 160, after: 60 }, keepNext: true,
      children: [new ImageRun({ type: 'png', data: fs.readFileSync(file), transformation: { width, height } })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 200 },
      children: [new TextRun({ text: `Рисунок ${figureNo} — ${caption}`, size: 24 })] }),
  ]
}
