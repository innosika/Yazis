function runs(text, base = {}) {
  // **жирный**, _курсив_, `код`
  const out = []
  const re = /(\*\*[^*]+\*\*|_[^_]+_|`[^`]+`)/g
  let pos = 0
  for (const m of text.matchAll(re)) {
    if (m.index > pos) out.push(new TextRun({ text: text.slice(pos, m.index), ...base }))
    const t = m[0]
    if (t.startsWith('**')) out.push(new TextRun({ text: t.slice(2, -2), bold: true, ...base }))
    else if (t.startsWith('`')) out.push(new TextRun({ text: t.slice(1, -1), font: 'DejaVu Sans Mono', size: 22, ...base }))
    else out.push(new TextRun({ text: t.slice(1, -1), italics: true, ...base }))
    pos = m.index + t.length
  }
  if (pos < text.length) out.push(new TextRun({ text: text.slice(pos), ...base }))
  return out
}

