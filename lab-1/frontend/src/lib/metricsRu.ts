/** Short display label for a metric in the current language. */
export function metricLabel(spec: Pick<MetricSpec, "key" | "label">): string {
  return getLang() === "ru" ? (LABEL_RU[spec.key] ?? spec.label) : spec.label;
}

export function metricDescription(spec: MetricSpec): string {
  return getLang() === "ru" ? (RU[spec.key] ?? spec.description) : spec.description;
}

/** Caveat notes arrive from the backend in English with numbers embedded; translate by shape. */
export function translateCaveat(note: string): string {
  if (getLang() !== "ru") return note;
  const precision = note.match(/^precision \(set\): with R = 1 it cannot exceed 1\/top_k \(= ([\d.]+) for top_k = (\d+)\)/);
  if (precision) {
    return `точность (множественная): при R = 1 не может превысить 1/top_k (= ${precision[1]} при top_k = ${precision[2]}); измеряет длину выдачи, а не качество`;
  }
  const setNote = note.match(/^precision and recall are set measures over the whole returned list \(top_k = (\d+)\)/);
  if (setNote) {
    return `точность и полнота — множественные меры по всей выдаче (top_k = ${setNote[1]}); их значения зависят от длины выдачи`;
  }
  return t(note);
}
